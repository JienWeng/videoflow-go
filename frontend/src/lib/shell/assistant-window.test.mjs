import assert from 'node:assert/strict';
import {clampWindow,readWindowLayout,clampWindowHeight,windowHeightLimits} from './assistant-window.mjs';
assert.deepEqual(clampWindow({x:-200,y:-10},{width:1000,height:800},420,600),{x:12,y:12});
assert.deepEqual(clampWindow({x:9999,y:9999},{width:1000,height:800},420,600),{x:568,y:188});
assert.deepEqual(clampWindow({x:250,y:80},{width:1000,height:800},420,600),{x:250,y:80});
assert.deepEqual(clampWindow({x:500,y:600},{width:600,height:400},420,376),{x:168,y:12});
assert.deepEqual(clampWindow({x:NaN,y:Infinity},{width:1000,height:800},420,600),{x:568,y:188});
assert.equal(readWindowLayout('invalid'),null);
assert.equal(readWindowLayout('{"mode":"floating","x":-1,"y":90,"width":450}')?.mode,'floating');
assert.equal(readWindowLayout('{"mode":"bad"}'),null);
assert.equal(readWindowLayout('{"mode":"floating","x":"9999","y":null}')?.position,null);
assert.equal(readWindowLayout('{"mode":"docked","width":99999}')?.width,undefined);
assert.deepEqual(windowHeightLimits(800),{min:360,max:776});
assert.deepEqual(windowHeightLimits(800,200),{min:360,max:588});
assert.deepEqual(windowHeightLimits(300),{min:276,max:276});
assert.equal(clampWindowHeight(100,800),360);
assert.equal(clampWindowHeight(900,800),776);
assert.equal(clampWindowHeight(680,800,200),588);
assert.equal(clampWindowHeight(480,800,100),480);
assert.equal(clampWindowHeight(Infinity,800),680);
assert.equal(clampWindowHeight(680,10),0);
assert.equal(readWindowLayout('{"mode":"floating","height":480}')?.height,480);
assert.equal(readWindowLayout('{"mode":"floating","height":100}')?.height,undefined);
assert.equal(readWindowLayout('{"mode":"floating","height":"680"}')?.height,undefined);
assert.equal(readWindowLayout('{"mode":"floating","height":999999}')?.height,undefined);
assert.equal(readWindowLayout('{"mode":"floating"}')?.height,undefined);
console.log('PASS 24 assistant-window assertions');
